"""Generate KitsuneUI_Sundown's sprites and its patches for KitsuneUI's hard-coded colours.

Sprites: same-name glass in dusk plum (a later atlas wins on a shared name, so the
"midnight" glass restyles and the other glass colours keep working), plus the hairline
bar and ring gauge shapes under sd_ names.

Patches: KitsuneUI and its add-ons write their palette straight into many attributes,
some inside expressions. This applies every patch to each game line's files, the same
way check_patches.py does, and writes one exact-value <set> per distinct attribute still
holding one of those colours. A value only one game line or add-on has goes in a
conditional, so nothing misses. Alpha is kept.

    python tools/gen_sundown.py --game 1.3.40.10 "<V3.4>/Data/Config" --game 1.3.30.17 "<V3.3>/Data/Config"

Writes a block into KitsuneUI_Sundown/Config/<XUi folder>/<file>.xml between the GENERATED
markers; anything outside the markers is hand-written and kept. Run it again after a
change to any add-on's colours.
"""

import argparse
import re
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

from lxml import etree
from PIL import Image, ImageChops

import check_patches
import gen_sprites as gs

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "KitsuneUI_Sundown"
SOURCES = ["XUi_Common/styles.xml", "XUi_Common/templates.xml", "XUi_InGame/windows.xml", "XUi_InGame/templates.xml",
           "XUi_Menu/windows.xml", "XUi_Menu/templates.xml"]
ADDONS = {"KitsuneUI_JobPreview": "mod_loaded('KitsuneUI_JobPreview')",
          "KitsuneUI_Practice": "mod_loaded('KitsuneUI_Practice') && mod_loaded('KitsuneShugyo')",
          "KitsuneUI_Settings": "mod_loaded('KitsuneUI_Settings')"}
SHUGYO = "KitsuneShugyo"
V34 = (1, 3, 40)

# Kitsunebi's colours -> Sundown's. The navies are KitsuneUI's dark fills and move handles.
COLOURS = {
    (111, 227, 255): (255, 105, 170),   # fox-fire -> hot pink
    (217, 184, 115): (170, 150, 235),   # gold -> lavender
    (30, 84, 118): (120, 44, 104),      # selection -> magenta plum
    (40, 92, 112): (150, 60, 130),      # button hover
    (40, 60, 96): (66, 58, 92),         # row hover
    (150, 175, 255): (170, 150, 235),   # edges -> lavender
    (12, 14, 30): (28, 26, 42),         # charcoal indigo
    (6, 8, 20): (16, 14, 26),
    (18, 22, 44): (42, 40, 60),
}
COLOUR_RE = re.compile(r"(?<![\d,.])(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})(?![\d.])")

# Darker charcoal glass with tight corners; the header is the same glass as the body,
# split from it only by the hairline.
GLASS_TOP = (28, 26, 42)
GLASS_BOTTOM = (20, 18, 30)
GLASS_HDR = (24, 22, 36)
GLASS_BODY = (24, 22, 36)
GLASS_A_TOP = 238
GLASS_A_BOTTOM = 230
RADIUS = 5
PINK = (255, 105, 170)
EDGE = (170, 150, 235)
LAVENDER = (170, 150, 235)

BEGIN = "<!-- ===== GENERATED by tools/gen_sundown.py: Kitsunebi's literal colours -> Sundown. Do not edit by hand. ===== -->"
END = "<!-- ===== END GENERATED ===== -->"


def recolour(value):
    def swap(m):
        rgb = tuple(int(g) for g in m.groups())
        return ",".join(str(c) for c in COLOURS[rgb]) if rgb in COLOURS else m.group(0)
    return COLOUR_RE.sub(swap, value)


def hand_written(path):
    """The patch file without its generated block, or None if there isn't one."""
    if not path.exists():
        return None
    return re.sub(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\s*", "", path.read_text(encoding="utf-8"), flags=re.S)


def scan(config, rel, mods, version):
    """Every (attribute, value) left holding a Kitsunebi colour once these mods are applied,
    with Sundown's hand-written patches last."""
    check_patches.LOADED.clear()
    check_patches.LOADED.update(mods)
    check_patches.LOADED.update({SHUGYO, MOD.name})
    check_patches.GAME_VERSION = version
    target = Path(config) / rel
    if not target.exists():
        return set()
    root = etree.parse(str(target)).getroot()
    for mod in mods:
        patch = ROOT / mod / "Config" / rel
        if patch.exists():
            check_patches.apply(root, etree.parse(str(patch)).getroot(), mod)
    own = hand_written(MOD / "Config" / rel)
    if own:
        check_patches.apply(root, etree.fromstring(own.encode("utf-8")), MOD.name)
    found = set()
    for el in root.iter():
        if isinstance(el.tag, str):
            found.update((k, v) for k, v in el.attrib.items() if recolour(v) != v)
    return found


def patch_line(attr, value):
    if "'" in value and '"' in value:
        raise SystemExit(f"Can't quote this value for an xpath: {value}")
    literal = f'"{value}"' if "'" in value else f"'{value}'"
    return f"<set xpath={quoteattr(f'//*[@{attr}={literal}]/@{attr}')}>{escape(recolour(value))}</set>"


def gen_patches(games):
    for rel in SOURCES:
        # (attr, value) -> the (game, add-on) pairs it turns up on; add-on None is core.
        seen = {}
        lines = sorted(games)
        for version, config in games.items():
            core = scan(config, rel, ["KitsuneUI"], version)
            for entry in core:
                seen.setdefault(entry, set()).add((version, None))
            for addon in ADDONS:
                for entry in scan(config, rel, ["KitsuneUI", addon], version) - core:
                    seen.setdefault(entry, set()).add((version, addon))
        groups = {}
        for entry, where in seen.items():
            versions = {v for v, _ in where}
            addons = {a for _, a in where}
            tests = []
            if len(versions) < len(lines):
                tests.append("game_version() >= version(1,3,40)" if max(versions)[:3] >= V34 else "game_version() < version(1,3,40)")
            if None not in addons:
                joined = " || ".join(ADDONS[a] for a in sorted(addons))
                tests.append(f"({joined})" if len(addons) > 1 else joined)
            groups.setdefault(" && ".join(tests), []).append(entry)
        write_block(MOD / "Config" / rel, groups)
        print(f"{rel}: {len(seen)} literal colours")


def write_block(path, groups):
    existing = hand_written(path)
    if not groups:
        if existing is not None:
            path.write_text(existing, encoding="utf-8")
        return
    out = ["\t" + BEGIN]
    for test in sorted(groups):
        lines = [patch_line(*e) for e in sorted(groups[test])]
        if test:
            out += ["\t<conditional>", f"\t\t<if cond={quoteattr(test)}>"]
            out += ["\t\t\t" + l for l in lines]
            out += ["\t\t</if>", "\t</conditional>"]
        else:
            out += ["\t" + l for l in lines]
    out.append("\t" + END)
    body = "\n".join(out) + "\n\n"
    text = existing if existing is not None else "<configs>\n\n</configs>\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.replace("</configs>", body + "</configs>"), encoding="utf-8")


def ring(size, thick):
    img = Image.new("RGBA", (size * gs.SS, size * gs.SS), (255, 255, 255, 0))
    img.putalpha(gs.ring_mask(size, size, size // 2, thick))
    return gs.down(img)


def ring_hatch(size, thick):
    img = gs.hatch_pill(size, size, size // 2, pitch=4)
    img.putalpha(ImageChops.multiply(img.getchannel("A"), ring(size, thick).getchannel("A")))
    return img


def gradient(w, h, stops, horizontal=False):
    """A straight gradient through (position 0..1, (r, g, b, a)) stops."""
    img = Image.new("RGBA", (w, h))
    px = img.load()
    span = w if horizontal else h
    for i in range(span):
        f = i / max(span - 1, 1)
        for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
            if p0 <= f <= p1:
                k = (f - p0) / max(p1 - p0, 1e-6)
                c = tuple(round(a + (b - a) * k) for a, b in zip(c0, c1))
                break
        for j in range(h if horizontal else w):
            px[(i, j) if horizontal else (j, i)] = c
    return img


def selected_row(w=128, h=32, r=2):
    """Magenta fading to clear on the right, with a hot pink bar down the left edge.
    The bar sits inside the 8px slice border, so it stays 4px wide at any row width."""
    img = gradient(w, h, [(0, (178, 56, 168, 225)), (0.5, (150, 50, 140, 110)), (1, (120, 44, 104, 0))], horizontal=True)
    img.paste(PINK + (255,), (0, 0, 4, h))
    img.putalpha(ImageChops.multiply(img.getchannel("A"), gs.solid_round(w, h, r).getchannel("A")))
    return img


def dusk_backdrop(w=256, h=144):
    """A full-screen dusk wash: deep indigo, darker at the top, with a magenta glow
    rising from the bottom left and a faint lavender haze top right."""
    img = Image.new("RGBA", (w, h))
    px = img.load()
    glows = [((0.08, 1.1), 0.85, (178, 56, 168), 0.58), ((0.95, -0.15), 0.7, LAVENDER, 0.16)]
    for y in range(h):
        v = y / (h - 1)
        base = [12 + 10 * v, 10 + 6 * v, 20 + 12 * v]
        for x in range(w):
            c = list(base)
            for (cx, cy), radius, rgb, strength in glows:
                d = (((x / (w - 1) - cx) * w / h) ** 2 + (v - cy) ** 2) ** 0.5 / (radius * w / h)
                k = strength * max(0.0, 1 - d) ** 2
                c = [a + (b - a) * k for a, b in zip(c, rgb)]
            px[x, y] = tuple(round(a) for a in c) + (255,)  # fully opaque: even 250 let the world show through
    return img


def corner_glow(size=128, rgb=(178, 56, 168), peak=150):
    """A soft glow spreading from the bottom left corner, clear by the far edges."""
    img = Image.new("RGBA", (size, size), rgb + (0,))
    px = img.load()
    for y in range(size):
        for x in range(size):
            d = ((x / (size - 1)) ** 2 + (1 - y / (size - 1)) ** 2) ** 0.5
            px[x, y] = rgb + (round(peak * max(0.0, 1 - d) ** 2),)
    return img


def go_button(w=64, h=32, r=4):
    """The Start button: magenta into hot pink, left to right."""
    img = gradient(w, h, [(0, (178, 56, 168, 255)), (1, PINK + (255,))], horizontal=True)
    img.putalpha(gs.solid_round(w, h, r).getchannel("A"))
    return img


def gen_sprites():
    # glass_panel and glass_part take their hairline from these, and popup_chip all of it.
    gs.GOLD = LAVENDER
    gs.EDGE = EDGE
    gs.GLASS_TOP = GLASS_TOP
    gs.GLASS_BOTTOM = GLASS_BOTTOM
    gs.GLASS_A_TOP = GLASS_A_TOP
    gs.GLASS_A_BOTTOM = GLASS_A_BOTTOM
    r = RADIUS
    tall = dict(top=GLASS_TOP, bottom=GLASS_BOTTOM, edge_rgb=EDGE)
    gs.write_atlas(MOD / "UIAtlases" / "UIAtlas", {
        "ku_panel": (gs.glass_panel(64, r, **tall), 10),
        "ku_panel_sm": (gs.glass_panel(40, r - 1, **tall), 8),
        "ku_disc": (gs.glass_panel(200, 100, **tall), 0),
        "ui_game_panel_header": (gs.glass_part(64, 48, r, GLASS_TOP + (GLASS_A_TOP,), GLASS_HDR + (GLASS_A_TOP,), True, False,
                                               divider=True, hairline=True, edge_rgb=EDGE), (8, 8, 8, 4)),
        "ku_panel_body": (gs.glass_part(64, 48, r, GLASS_BODY + (GLASS_A_TOP,), GLASS_BOTTOM + (GLASS_A_BOTTOM,), False, True,
                                        edge_rgb=EDGE), (8, 8, 4, 8)),
        # Item slots: KitsuneUI's well, ring and hover ring with tight corners.
        "ku_slot_fill": (gs.solid_round(32, 32, 4), 10),
        "ku_slot_ring": (gs.ring(32, 32, 4, 1.25), 10),
        "ku_slot_ring2": (gs.ring(32, 32, 4, 2.0), 10),
        # Slots past carry capacity: pink stripes over the well, drawn at slot size.
        "sd_slot_hatch": (gs.hatch_pill(72, 72, 4, pitch=8), 0),
        # The backpack section bar's smoke band: dark at the screen top, clear at the foot.
        "sd_smoke": (gradient(8, 128, [(0, (14, 12, 22, 215)), (0.6, (14, 12, 22, 110)), (1, (14, 12, 22, 0))]), 0),
        "ui_game_popup": (gs.popup_chip(), 12),
        "sd_bar": (gs.solid_round(180, 8, 4), 0),
        "sd_hatch": (gs.hatch_pill(180, 8, 4, pitch=5), 0),
        "sd_ring": (ring(56, 5), 0),
        "sd_ring_hatch": (ring_hatch(56, 5), 0),
        "sd_ring_thin": (ring(72, 3), 0),
        "sd_disc": (gs.solid_round(56, 56, 28), 0),
        "sd_line": (Image.new("RGBA", (8, 2), (255, 255, 255, 255)), 0),
        # The pause and main menu column: smoke at the top, hot magenta at the foot.
        "sd_rail": (gradient(32, 256, [(0, (36, 24, 48, 150)), (0.35, (92, 44, 108, 205)), (1, (178, 56, 168, 240))]), 0),
        "sd_scrim": (gradient(64, 8, [(0, (20, 18, 28, 80)), (1, (20, 18, 28, 140))], horizontal=True), 0),
        # Behind Options opened in game, where there is no menu video to show.
        "sd_backdrop": (dusk_backdrop(), 0),
        # Play Game: a wash darkening the video behind the left panel, the magenta glow
        # rising from the bottom left corner, and the solid Start button.
        "sd_wash": (gradient(64, 8, [(0, (20, 18, 28, 150)), (1, (20, 18, 28, 0))], horizontal=True), 0),
        "sd_glow": (corner_glow(), 0),
        "sd_btn_go": (go_button(), 8),
    })
    gs.write_atlas(MOD / "UIAtlases" / "KitsuneRows", {
        # Idle and hover rows: the game tints this 64 / 96 grey, so the lavender barely shows idle.
        "menu_empty": (gs.solid_round(32, 32, 2, (200, 185, 255, 30)), 4),
        "ui_game_select_row": (selected_row(), (8, 8, 8, 8)),
    })


def main():
    parser = argparse.ArgumentParser(description="Generate KitsuneUI_Sundown's sprites and colour patches.")
    parser.add_argument("--game", nargs=2, action="append", required=True, metavar=("VERSION", "CONFIG"))
    args = parser.parse_args()
    games = {tuple(int(p) for p in v.split(".")): c for v, c in args.game}
    gen_sprites()
    gen_patches(games)


if __name__ == "__main__":
    main()
