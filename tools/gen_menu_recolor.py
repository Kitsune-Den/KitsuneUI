"""Generate KitsuneUI's patches that recolour the vanilla UI's hard-coded red.

The menus (and a few shared templates) don't use the palette: they write the
7 Days red, 228,18,21 (and 179,11,11 / 200,0,0 / [red]), straight into ~100
attributes, sometimes inside expressions. This scans the vanilla XUi files and
writes one exact-value <set> per distinct attribute, so a vanilla update that
changes a value just stops that one patch from applying (and logs it).

Role decides the colour, alpha kept:
  fills (a sprite's own colour unless it's an outline, backcolor, bg_*) -> deep teal
  everything else (text, borders, outlines, hover colours)              -> fox-fire cyan
  incompatible_version_color / missing-world red                        -> kept

    python tools/gen_menu_recolor.py "<7 Days To Die>/Data/Config"

Writes a generated block into KitsuneUI/Config/<XUi folder>/<file>.xml between
the GENERATED markers; anything outside the markers is hand-written and kept.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "KitsuneUI" / "Config"

SOURCES = ["XUi_Menu/windows.xml", "XUi_Menu/templates.xml", "XUi_Common/templates.xml", "XUi_Common/styles.xml"]

REDS = {(228, 18, 21), (179, 11, 11), (200, 0, 0)}
CYAN = (111, 227, 255)
TEAL = (30, 84, 118)
KEEP_ATTRS = {"incompatible_version_color"}

BEGIN = "\t<!-- ===== GENERATED by tools/gen_menu_recolor.py: vanilla red -> Kitsunebi. Do not edit by hand. ===== -->"
END = "\t<!-- ===== END GENERATED ===== -->"

COLOR_RE = re.compile(r"(?P<pre>color\(\s*|')?(?P<r>\d{1,3})\s*,\s*(?P<g>\d{1,3})\s*,\s*(?P<b>\d{1,3})(?P<a>\s*,\s*\d{1,3})?")


def role(tag, attr, el):
    a = attr.lower()
    if any(k in a for k in ("border", "text", "font", "thumb")):
        return CYAN
    if a.startswith("bg") or a in ("backcolor", "bg_color", "backgroundcolor"):
        return TEAL
    if tag in ("sprite", "filledsprite") and a == "color":
        # an outline sprite is a border; a filled one is a fill
        return CYAN if el.get("fillcenter", "").lower() == "false" else TEAL
    if tag == "style_entry":
        # listentry.background (fill) vs listentry.border
        return TEAL if "background" in (el.get("_style") or "") else CYAN
    return CYAN


def recolor(value, target):
    hit = False

    def sub(m):
        nonlocal hit
        rgb = (int(m["r"]), int(m["g"]), int(m["b"]))
        if rgb not in REDS:
            return m.group(0)
        hit = True
        a = m["a"] or ""
        return f"{m['pre'] or ''}{target[0]},{target[1]},{target[2]}{a.replace(' ', '')}"

    new = COLOR_RE.sub(sub, value)
    if "[red]" in value:
        hit = True
        new = new.replace("[red]", "[kuAccent]")
    return new if hit else None


def xpath_literal(s):
    if '"' not in s:
        return f'"{s}"'
    if "'" not in s:
        return f"'{s}'"
    parts = s.split('"')
    return "concat(" + ", '\"', ".join(f'"{p}"' for p in parts) + ")"


def scan(path):
    tree = ET.parse(path)
    # remember which style an entry belongs to (for listentry.background vs border)
    for style in tree.getroot().iter("style"):
        for entry in style.iter("style_entry"):
            entry.set("_style", style.get("name", ""))
    found = {}
    for el in tree.getroot().iter():
        for attr, value in el.attrib.items():
            if attr.startswith("_") or attr in KEEP_ATTRS:
                continue
            if "invalid" in (el.get("name") or "").lower():   # red that means "can't": keep
                continue
            new = recolor(value, role(el.tag, attr, el))
            if new and new != value:
                found[(el.tag, attr, value)] = new
    return found


def write_block(target, lines):
    """Put the generated block FIRST in the file, so the hand-written patches after it
    always win (and never find their vanilla value already changed under them)."""
    target.parent.mkdir(parents=True, exist_ok=True)
    block = "\n".join([BEGIN, *lines, END])
    if target.exists():
        text = target.read_text(encoding="utf-8")
        if BEGIN in text:
            pre, rest = text.split(BEGIN, 1)
            text = pre.rstrip() + "\n" + rest.split(END, 1)[1].lstrip("\n")
        text = text.replace("<configs>", "<configs>\n\n" + block + "\n", 1)
    else:
        text = "<configs>\n\n" + block + "\n\n</configs>\n"
    target.write_text(text, encoding="utf-8")


def main():
    vanilla = Path(sys.argv[1])
    total = 0
    for rel in SOURCES:
        found = scan(vanilla / rel)
        lines = []
        for (tag, attr, old), new in sorted(found.items()):
            xp = f"//{tag}[@{attr}={xpath_literal(old)}]/@{attr}"
            lines.append(f"\t<set xpath={quoteattr(xp)}>{escape(new)}</set>")
        write_block(CONFIG / rel, lines)
        print(f"{rel}: {len(lines)} patches")
        total += len(lines)
    print(f"total {total}")


if __name__ == "__main__":
    main()
